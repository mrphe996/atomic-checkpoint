# 4.1 The Periodic Table · 9Cm.01
# =====================================================================================================
READ["4.1"] = L(
    H("Why helium and not hydrogen?",
      "Party balloons are filled with helium, even though hydrogen is lighter and cheaper.",
      "What property of hydrogen makes it a bad choice? (Think about what it does near a flame.)"),
    I("The structure of the atom",
      "The **nuclear model**: a tiny, dense **nucleus** containing **protons** (+) and **neutrons** (0), with **electrons** (−) moving in **shells** around it. Most of the atom is empty space.",
      then=["Rutherford's gold foil experiment (Stage 8) gave the evidence: most alpha particles passed straight through gold foil, but a few bounced back from a tiny dense nucleus.",
            "An atom has equal numbers of protons and electrons, so it is electrically **neutral**."]),
    I("Atomic number and mass number",
      "Each element in the Periodic Table has two numbers.",
      table=[["Number", "Meaning"], ["**atomic number**", "number of **protons** (= number of electrons in a neutral atom)"],
             ["**mass number**", "number of **protons + neutrons** (together called nucleons)"], ["neutrons", "= mass number − atomic number"]]),
    W("Counting particles",
      "Aluminium has atomic number 13 and mass number 27. How many protons, electrons and neutrons does an atom have?",
      [("protons = 13", "atomic number"), ("electrons = 13", "neutral atom"), ("neutrons = 27 − 13 = 14", "mass number − atomic number")], "13 protons, 13 electrons, 14 neutrons"),
    Y("Neutrons",
      num("s9u04r11", "Potassium has atomic number 19 and mass number 39. How many neutrons does a potassium atom have?", 20, "neutrons = mass number − atomic number.",
          "39 − 19 = 20.", errs=[(58, "Subtract, do not add."), (19, "That is the number of protons.")])),
    I("Real life: elements at work",
      "Each element's use depends on its properties, which depend on the structure of its atoms.",
      fig=CARD("Elements at work", [{"icon": "planet", "t": "Helium", "d": "less dense than air, unreactive: balloons and airships"}, {"icon": "phone", "t": "Lithium", "d": "lightest metal, loses an electron easily: rechargeable batteries"},
                                    {"icon": "scanner", "t": "Silicon", "d": "conducts a little: computer chips"}, {"icon": "car2", "t": "Hydrogen", "d": "burns to make only water: clean fuel"}], 4)),
    I("Arranging electrons: the first 20 elements",
      "Electrons fill shells from the inside out: **2** in the first, up to **8** in the second, up to **8** in the third, then the fourth.",
      fig={"kind": "atom", "shells": [2, 8, 8, 2], "p": 20, "n": 20, "title": "calcium 2, 8, 8, 2"},
      table=[["Element", "Atomic number", "Electronic structure"], ["lithium", "3", "2, 1"], ["oxygen", "8", "2, 6"], ["neon", "10", "2, 8"], ["sodium", "11", "2, 8, 1"],
             ["sulfur", "16", "2, 8, 6"], ["argon", "18", "2, 8, 8"], ["potassium", "19", "2, 8, 8, 1"], ["calcium", "20", "2, 8, 8, 2"]]),
    Y("Electronic structure",
      mcq("s9u04r12", "Chlorine has atomic number 17. What is its electronic structure?",
          [("2, 8, 7", True, "Yes – 2 + 8 + 7 = 17."), ("2, 7, 8", False, "Fill the second shell (8) before the third."), ("8, 8, 1", False, "The first shell holds only 2."),
           ("2, 15", False, "The second shell holds up to 8.")],
          "2 first, then 8, then the rest.", "17 = 2 + 8 + 7.")),
    K("Key points",
      "Nuclear model: protons and neutrons in a tiny nucleus; electrons in shells; mostly empty space.",
      "**Atomic number** = protons (= electrons); **mass number** = protons + neutrons.",
      "Shells fill 2, 8, 8, 2 for the first 20 elements.",
      "An element's uses depend on its properties, which depend on its atomic structure."),
    book=BK(
        [("atomic number", "the number of protons in an atom"), ("mass number", "the number of protons plus neutrons"), ("nucleon", "a proton or neutron"),
         ("electronic structure", "how the electrons are arranged in shells, e.g. 2, 8, 1")],
        [], [],
        [Ex("Find the protons, electrons and neutrons in: (a) carbon (6, 12) (b) sodium (11, 23) (c) calcium (20, 40).", ans="(a) 6, 6, 6 (b) 11, 11, 12 (c) 20, 20, 20"),
         Ex("Write the electronic structure of: (a) nitrogen (7) (b) magnesium (12) (c) argon (18).", ans="(a) 2, 5 (b) 2, 8, 2 (c) 2, 8, 8"),
         Ex("Draw a shell diagram of a sodium atom.", ans="nucleus 11p 12n; shells with 2, 8 and 1 electrons"),
         Ex("Back to 'Start here': why is helium used in balloons instead of hydrogen?", ans="Hydrogen is flammable and can explode; helium is unreactive and still much less dense than air.", think=True)],
        ["describe the nuclear model of the atom", "use atomic and mass numbers", "write the electronic structure of the first 20 elements"],
        look=["atomic and mass numbers", "electronic structures table"],
        note="Read it after the video: the nuclear atom, atomic and mass numbers and electron shells (answers at the back)."),
)

