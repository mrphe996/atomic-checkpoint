# 4.2 More about the Periodic Table · 9Cm.01, 9Cp.01
# =====================================================================================================
READ["4.2"] = L(
    H("Kept under oil",
      "In a school laboratory, lumps of sodium and potassium are stored in jars of oil – never in water or open air.",
      "Why might these metals be so dangerous? Make a prediction."),
    I("Groups and periods",
      "In the Periodic Table, **rows** are **periods** and **columns** are **groups**.",
      fig={"kind": "sciPeriodic", "group": 1},
      table=[["", "Tells you"], ["**period number**", "the number of occupied electron shells"], ["**group number** (groups 1–2, 13–18)", "the number of outer-shell electrons (group 18: full outer shell)"]],
      then=["Elements in the same group have the **same number of outer electrons**, so they have **similar chemical properties**. Group 1: lithium 2, 1; sodium 2, 8, 1; potassium 2, 8, 8, 1."]),
    I("Predict, watch, explain: Group 1 metals in water",
      "Small pieces of lithium, sodium and potassium are dropped into water behind a safety screen.",
      table=[["Metal", "What happens"], ["lithium", "floats and fizzes gently"], ["sodium", "melts into a ball and whizzes around"], ["potassium", "reacts violently; the hydrogen catches fire with a lilac flame"]],
      then=["All three have **one outer electron**, which they lose when they react. Down the group the atoms are **bigger**, so the outer electron is **further from the nucleus** and held less strongly – it is lost more easily, so reactivity increases."]),
    I("Trends in Group 1",
      "The Group 1 elements are the **alkali metals**.",
      table=[["Reactants", "", "Products"], ["**alkali metal + water**", "→", "**metal hydroxide + hydrogen**"], ["sodium + water", "→", "sodium hydroxide + hydrogen"]],
      then=["The hydroxides dissolve to make **alkaline** solutions – hence 'alkali metals'.",
            "Down the group: **reactivity increases**; melting and boiling points **decrease**; the metals are soft enough to cut with a knife."]),
    I("Real data: melting points of Group 1",
      "Melting points of the first five alkali metals:",
      fig={"kind": "barchart", "labels": ["lithium", "sodium", "potassium", "rubidium", "caesium"], "values": [181, 98, 64, 39, 28.5], "ymax": 200, "step": 40, "ylabel": "melting point (°C)", "xlabel": "element"},
      then=["The melting point falls down the group. Caesium would melt on a very hot day. We can predict that francium, next in the group, would melt at an even lower temperature."]),
    Y("Most reactive",
      mcq("s9u04r21", "Which Group 1 metal would react most violently with water?",
          [("caesium", True, "Yes – it is lowest of these, so its outer electron is lost most easily."), ("lithium", False, "Lithium is the least reactive."),
           ("sodium", False, "Sodium is less reactive than those below it."), ("potassium", False, "Caesium is further down.")],
          "Reactivity increases down the group.", "The lower in Group 1, the more reactive.")),
    Y("Same group?",
      grid("s9u04r22", "Do these elements have similar chemical properties (same group)?", ["Similar", "Not similar"],
           [("lithium and potassium", "Similar"), ("fluorine and chlorine", "Similar"), ("sodium and chlorine", "Not similar"), ("helium and neon", "Similar"), ("carbon and calcium", "Not similar")],
           "Are they in the same column?", "Li/K (group 1), F/Cl (group 17), He/Ne (group 18) share groups; the others do not.")),
    K("Key points",
      "Rows = **periods** (number of shells); columns = **groups** (number of outer electrons).",
      "Same group → same number of outer electrons → similar properties.",
      "Alkali metal + water → metal hydroxide + hydrogen.",
      "Down Group 1: reactivity increases, melting point decreases."),
    book=BK(
        [("group", "a column of the Periodic Table; elements with the same number of outer electrons"), ("period", "a row of the Periodic Table"),
         ("alkali metals", "the Group 1 elements"), ("trend", "a pattern of change, e.g. down a group")],
        [], [],
        [Ex("Why do lithium, sodium and potassium have similar chemical properties?", ans="They each have one electron in their outer shell."),
         Ex("Write a word equation for potassium reacting with water.", ans="potassium + water → potassium hydroxide + hydrogen"),
         Ex("Explain why reactivity increases down Group 1.", ans="Atoms get bigger, the outer electron is further from the nucleus and held less strongly, so it is lost more easily."),
         Ex("Quick quiz.", ("What is the mass number?", "protons + neutrons"), ("Electronic structure of sodium?", "2, 8, 1"),
            ("What gas forms when sodium reacts with water?", "hydrogen"), ("Trend in melting point down Group 1?", "it decreases")),
         Ex("Why are sodium and potassium stored under oil?", ans="They react quickly with oxygen and water vapour in the air; the oil keeps air and moisture away.", think=True)],
        ["link groups and periods to electron shells", "explain why elements in a group have similar properties", "describe trends in Group 1"],
        look=["Group 1 in water", "the melting point trend"],
        note="Read it after the video: groups, periods and the alkali metals, plus a quick quiz (answers at the back)."),
)
