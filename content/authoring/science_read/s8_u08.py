         Ex("A cyclist rides 6 km in 15 min, rests for 5 min, then rides 4 km in 10 min. What is her average speed in km/h?", ans="10 km in 30 min = 0.5 h → 20 km/h"),
         Ex("Back to 'Start here': work out each speed in km/h and say who is fastest.", ans="Maya 15 km/h, Ravi 24 km/h, Leo about 4.3 km/h – Ravi is fastest"),
