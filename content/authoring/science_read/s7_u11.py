def FLOW(*boxes, title=None):
    """an energy flow diagram: boxes = store names; transfers drawn as arrows between them"""
    n = len(boxes); xs = [72 + i * (336 / (n - 1)) for i in range(n)]
    return {"kind": "flow", "nodes": [{"x": round(x), "y": 40, "t": t, **({"c": "#FFF6D6"} if 0 < i < n - 1 else {})} for i, (x, t) in enumerate(zip(xs, boxes))],
            "edges": [[i, i + 1, ""] for i in range(n - 1)], "w": 136, "vb": "0 0 480 80"}


