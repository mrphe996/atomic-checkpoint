# -*- coding: utf-8 -*-
"""Stage 3 · Unit 14 Angles and movement – v4 lessons (Camday's own text, numbers and questions)."""
from maths_notes_v4.kit4 import H, R, I, M, W, Y, ER, X, T, K, L, num, mcq, explain
from maths_notes_v4.s4_u08 import CMP
from maths_notes_v4.s4_u18 import DIR

NOTES = {}
PT = lambda angles, labels=None: dict({"kind": "anglept", "angles": angles, "start": 0}, **({"labels": labels} if labels else {}))
CO = lambda x, y, **k: dict({"kind": "coord", "x": x, "y": y}, **k)
TURN = lambda id, prompt, right, **kw: mcq(id, prompt, [(t, t == right, "") for t in ["quarter turn", "half turn", "three-quarter turn", "whole turn"]], "", "", fixed=True, **kw)

# =====================================================================================================
# 14.1 Angles and turns
# =====================================================================================================
