def money(id, prompt, d, c, hint, reason, **kw):
    """an amount like $3.45"""
    s = f"${d}.{c:02d}"
    rx = rf"/^\s*\$?\s*{d}\s*[.,]\s*{c:02d}\s*$/"
    return short(id, prompt + " Write it like $2.50.", [s, rx], hint, reason, skill="Application", **kw)


