NOTES = {}
CLOCK = lambda h, m: {"kind": "clock", "h": h, "m": m}


def t12(id, prompt, h, m, hint, reason, **kw):
    """a 12-hour digital time like 3:25"""
    s = f"{h}:{m:02d}"
    rx = rf"/^\s*0?{h}\s*[:.]\s*{m:02d}\s*(a\.?m\.?|p\.?m\.?)?\s*$/i"
    return short(id, prompt + " Write it like 4:05.", [s, rx], hint, reason, skill="Application", **kw)


