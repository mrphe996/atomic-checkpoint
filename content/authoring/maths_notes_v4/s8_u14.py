CO = lambda x, y, **k: dict({"kind": "coord", "x": x, "y": y}, **k)
P = lambda pts, l=None, c=None: dict({"pts": pts}, **({"l": l} if l else {}), **({"c": c} if c else {}))
BR = lambda a, b, deg, **k: dict({"kind": "bearing", "from": a, "to": b, "bearing": deg}, **k)


def pt(id, prompt, x, y, hint, reason, **kw):
    s = f"({x}, {y})"
    return short(id, prompt, [s, s.replace(" ", ""), f"{x},{y}", f"{x}, {y}"], hint, reason, **kw)


def bg(id, prompt, deg, hint, reason, **kw):
    return short(id, prompt + " Write three figures, e.g. 045.", [f"{deg:03d}", f"{deg:03d}°"], hint, reason, **kw)


