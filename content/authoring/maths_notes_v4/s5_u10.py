from maths_notes_v4.kit4 import H, R, I, M, W, Y, ER, X, T, K, L, num, mcq, explain

NOTES = {}
PT = lambda angles, labels=None, line=False: dict({"kind": "anglept", "angles": angles, "start": 0}, **({"labels": labels} if labels else {}), **({"line": True} if line else {}))


def ty(id, prompt, right, **kw):
    return mcq(id, prompt, [(w, w == right, "") for w in ["acute", "right", "obtuse", "straight"]], "", "", fixed=True, **kw)


