def hm(id, prompt, h, m, hint, reason, **kw):
    s = f"{h} h {m} min"
    rx = rf"/^\s*{h}\s*(h|hours?|hrs?)\s*(and\s*)?{m}\s*(min|mins|minutes?|m)\s*$/i"
    return short(id, prompt + " Write it like 2 h 15 min.", [s, rx], hint, reason, skill="Application", **kw)


def tm(id, prompt, t, hint, reason, **kw):
    h, m = t.split(":")
    rx = rf"/^\s*0?{int(h)}\s*[:.]\s*{m}\s*$/"
    return short(id, prompt + " Use the 24-hour clock, like 09:30.", [t, rx], hint, reason, skill="Application", **kw)


