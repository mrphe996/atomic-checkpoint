#!/usr/bin/env node
// Writes web/config.js from environment variables (public values only).
import fs from 'node:fs';
const e = (k, d = '') => process.env[k] || d;
const cfg = {
  // env: 'test' (staging, data may be reset) | 'production' (real families) | 'demo' (no server)
  env: e('ATOMIC_ENV', process.env.ATOMIC_MODE !== 'live' ? 'demo' : process.env.VERCEL_ENV === 'production' ? 'production' : 'test'),
  mode: e('ATOMIC_MODE', 'demo'), billing: e('BILLING', process.env.PADDLE_CLIENT_TOKEN ? 'paddle' : 'off'),
  apiBase: e('API_BASE', '/api'), directSignup: e('DIRECT_SIGNUP', 'off') === 'on', signupUrl: e('SIGNUP_URL', ''), supabaseUrl: e('SUPABASE_URL'), supabaseAnonKey: e('SUPABASE_ANON_KEY'),
  paddle: { env: e('PADDLE_ENV', 'sandbox'), token: e('PADDLE_CLIENT_TOKEN'), prices: { monthly: e('PADDLE_PRICE_MONTHLY'), yearly: e('PADDLE_PRICE_YEARLY') } },
  priceLabels: { monthly: e('PRICE_LABEL_MONTHLY', '£9.99 / month'), yearly: e('PRICE_LABEL_YEARLY', '£79 / year') },
  // stages learners cannot open yet (19 = Mathematics Stage 9); set LOCKED_STAGES= (empty) to open them
  lockedStages: e('LOCKED_STAGES', process.env.LOCKED_STAGES === '' ? '' : '17,18,19').split(',').map(x => Number(x.trim())).filter(Boolean),
  supportEmail: e('SUPPORT_EMAIL', 'support@example.com'), legalVersion: '2026-11-draft'
};
if (cfg.mode === 'live' && (!cfg.supabaseUrl || !cfg.supabaseAnonKey)) { console.error('ATOMIC_MODE=live needs SUPABASE_URL and SUPABASE_ANON_KEY'); process.exit(1); }
fs.writeFileSync(new URL('../web/config.js', import.meta.url), `/* generated by tools/write-config.mjs */\nwindow.ATOMIC_CONFIG = ${JSON.stringify(cfg, null, 2)};\n`);
console.log(`web/config.js written (env ${cfg.env}, mode ${cfg.mode}, billing ${cfg.billing})`);
