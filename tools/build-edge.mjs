#!/usr/bin/env node
// Builds the Supabase Edge Functions from the same handlers the Node tests use (api/*.js) and the shared rules.
//   supabase/functions/_shared/   public code (committed): rules, helpers, handlers
//   supabase/functions/api/       index.ts + answer keys (units.js, data/ – git-ignored, deployed only)
//   supabase/functions/signup/    index.ts
// EDGE_LIB=<url> makes the index files import _shared from that URL (e.g. a commit-pinned raw.githubusercontent.com path),
// so a deploy only uploads index.ts and the keys. Default: '../_shared' (local tests, `supabase functions deploy`).
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const F = path.join(ROOT, 'supabase/functions');
const LIB = process.env.EDGE_LIB || '../_shared';
const rd = (p) => fs.readFileSync(path.join(ROOT, p), 'utf8');
const wr = (p, s) => { fs.mkdirSync(path.dirname(path.join(F, p)), { recursive: true }); fs.writeFileSync(path.join(F, p), s); };
for (const d of ['_shared', 'api', 'signup']) fs.rmSync(path.join(F, d), { recursive: true, force: true });

const handler = (s, lib) => s.replace("from './_lib/supa.js'", `from './${lib}'`).replace(/\nexport default async function handler[\s\S]*$/, '\n');
wr('_shared/grade-core.js', rd('shared/grade-core.js')); wr('_shared/test-rules.js', rd('shared/test-rules.js'));
wr('_shared/supa.js', rd('edge/supa.js')); wr('_shared/mini.js', rd('edge/mini.js'));
for (const f of ['submit-test.js', 'marking.js', 'account.js']) wr('_shared/' + f, handler(rd('api/' + f), 'supa.js'));
wr('_shared/signup.js', handler(rd('api/signup.js'), 'mini.js'));

wr('api/index.ts', rd('edge/index.ts').replaceAll('__LIB__', LIB));
wr('signup/index.ts', rd('edge/signup-index.ts').replaceAll('__LIB__', LIB));
const units = fs.existsSync(path.join(ROOT, 'server/private')) ? fs.readdirSync(path.join(ROOT, 'server/private')).filter((f) => f.endsWith('.tests.json')).map((f) => f.replace('.tests.json', '')) : [];
let idx = '// generated by tools/build-edge.mjs – contains answer keys: never commit\n';
for (const u of units) {
  const pub = JSON.parse(rd('web/content/' + u + '.json')); const priv = JSON.parse(rd('server/private/' + u + '.tests.json'));
  const q = (x) => ({ id: x.id, obj: x.obj });
  const slim = { sections: pub.sections.map((s) => ({ id: s.id, stops: s.stops.map((x) => ({ id: x.id })), req: s.req.map(q), prac: s.prac.map(q) })) };
  wr('api/data/' + u + '.js', 'export default ' + JSON.stringify({ content: slim, papers: priv.papers }) + ';\n');
  idx += `import u_${u.replace(/-/g, '_')} from './data/${u}.js';\n`;
}
idx += 'export const UNITS = {' + units.map((u) => `'${u}': u_${u.replace(/-/g, '_')}`).join(', ') + '};\n';
wr('api/units.js', idx);
console.log(`edge functions built (lib ${LIB}) | units: ${units.join(', ') || 'none – answer keys missing'}`);
